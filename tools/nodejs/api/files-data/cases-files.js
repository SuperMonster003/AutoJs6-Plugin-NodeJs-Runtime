// Rhino / Node comparison cases of the files module (AutoJs6 api-coverage P3.2b).
// Each case is [id, expression] or [id, expression, nodeExpression]. Expressions are evaluated in order with files and
// D in scope; D is the absolute path of an empty writable directory the device script creates for the run (the Rhino
// and Node runs use different ones), so results hold relative names, contents, sizes and booleans, never absolute
// paths. Cases build on the files earlier cases left in D. Node expressions may return a Promise, which is awaited
// (open, toFile and readAssets return Promises of Java handles or values in Node). A Node expression of null skips
// the case in Node. Plain ES5 and arrow functions only, the file is evaluated by Rhino as well.

// The sorted names of a listing (a Java String[] in Rhino, an array in Node).
function filesNames(expression) {
    return "(function (a) { var r = []; for (var i = 0; i < a.length; i++) r.push(String(a[i])); return r.sort(); })(" + expression + ")";
}

// The unsigned values of a byte array (a Java byte[] in Rhino, a Uint8Array in Node).
function filesBytes(expression) {
    return "(function (b) { var r = []; for (var i = 0; i < b.length; i++) r.push(b[i] & 255); return r; })(" + expression + ")";
}

// The text a file handle reads, closed afterwards.
function filesOpenRead(args, read) {
    return [
        "(function () { var f = files.open(" + args + "); try { return f." + read + "; } finally { f.close(); } })()",
        "files.open(" + args + ").then(async f => { try { return await f.call('" + read.replace(/[(][)]$/, "") + "'); } finally { await f.call('close'); } })",
    ];
}

